#!/usr/bin/env node
// Generates supabase/migrations/20261012000002_exercise_library_seed.sql from the ExerciseDB
// dataset, as redistributed by github.com/hasaneyldrm/exercises-dataset (MIT, see NOTICE.md).
//
// The metadata is MIT so the generated SQL is committed. The images and animations are NOT —
// they are mirrored into Supabase Storage at setup time by scripts/sync-exercise-media.sh.
//
//   node scripts/build-exercise-library.mjs [path/to/exercises-data.js]
//
// The default source is an openGym checkout next to this repository; any file holding the
// `export const EXDB=[...]` array (or a plain JSON array) works.

import { readFile, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import path from 'node:path'

const DEFAULT_SOURCE = path.join(homedir(), 'work/openGym/frontend/src/lib/exercises-data.js')
const OUT = 'supabase/migrations/20261012000002_exercise_library_seed.sql'

// A stable uuid per exercise, so re-running the generator does not churn the migration and a
// plan that references an exercise keeps resolving. uuid v5-ish: a fixed namespace hashed with
// the upstream id, laid out as a v4-shaped uuid.
function uuidFor(extId) {
  // FNV-1a over the namespaced id, repeated with different offsets to fill 128 bits.
  const seed = `coachapp.exercises:${extId}`
  const bytes = []
  for (let round = 0; round < 4; round++) {
    let h = 0x811c9dc5 ^ (round * 0x9e3779b9)
    for (let i = 0; i < seed.length; i++) {
      h ^= seed.charCodeAt(i)
      h = Math.imul(h, 0x01000193) >>> 0
    }
    bytes.push((h >>> 24) & 0xff, (h >>> 16) & 0xff, (h >>> 8) & 0xff, h & 0xff)
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x40 // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80 // variant
  const hex = bytes.map((b) => b.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`
}

const quote = (value) =>
  value === null || value === undefined || value === '' ? 'null' : `'${String(value).replace(/'/g, "''")}'`

const quoteArray = (values) =>
  !values || values.length === 0
    ? 'null'
    : `array[${values.map((v) => quote(v)).join(', ')}]`

// Title-cases a dataset term for display: the dataset stores everything lower case.
const title = (s) =>
  !s ? null : s.replace(/(^|[\s/-])([a-z])/g, (_, pre, ch) => pre + ch.toUpperCase())

async function main() {
  const source = process.argv[2] ?? DEFAULT_SOURCE
  const raw = await readFile(source, 'utf8')
  const start = raw.indexOf('[')
  const end = raw.lastIndexOf(']')
  if (start < 0 || end < 0) throw new Error(`no JSON array found in ${source}`)
  const exercises = JSON.parse(raw.slice(start, end + 1))
  if (!Array.isArray(exercises) || exercises.length === 0) throw new Error('empty dataset')

  const rows = exercises.map((e) => {
    const instructions = Array.isArray(e.st) ? e.st.join('\n') : null
    return [
      quote(uuidFor(e.id)),
      quote(e.id),
      quote(title(e.n)),
      quote(title(e.mg ?? e.tg)),
      quote(title(e.eq)),
      quote(title(e.bp)),
      quote(title(e.tg)),
      quoteArray((e.sm ?? []).map(title)),
      quote(instructions),
      quote(e.img),
      quote(e.gif),
    ].join(', ')
  })

  const sql = `-- Generated by scripts/build-exercise-library.mjs -- do not edit by hand.
--
-- ${exercises.length} global exercises (coach_id null, so every coach and client can read them;
-- exercises_write keeps anyone from editing them through the API). Metadata and instructions come
-- from ExerciseDB v1 via github.com/hasaneyldrm/exercises-dataset under the MIT license; see
-- NOTICE.md. The matching images are not in this repository.

insert into public.exercises
    (id, ext_id, name, muscle_group, equipment, body_part, target, secondary_muscles, instructions, image_path, gif_path)
values
${rows.map((r) => `    (${r})`).join(',\n')}
on conflict (ext_id) do nothing;
`

  await writeFile(OUT, sql)
  console.log(`${OUT}: ${exercises.length} exercises`)
}

main().catch((err) => {
  console.error(err.message)
  process.exit(1)
})
